  /* geometry of a preset: carbon-centre radius, ion-accessible radius, water-accessible radius (nm) */
  function geometry(p) {
    const Rc = p.dC / 2;
    return { Rc, a: Rc - R_C_VDW, Rw: Rc - SIGMA_CO };
  }
  /* rigid-shell estimate: fraction of a first shell of radius r1 (ion on the axis) whose water oxygens fit inside a
     cylinder of radius Rw (two polar caps); 1 when the whole shell fits */
  function shellFraction(r1, Rw) { if (Rw >= r1) return 1; if (Rw <= 0) return 0; return 1 - Math.sqrt(1 - (Rw / r1) * (Rw / r1)); }

  /* solvation energies (kJ mol⁻¹) for the selected closure */
  function solvation(o) {
    const p = presetOf(o.preset), g = geometry(p), lin = LININGS[o.lining] || LININGS.carbon;
    const out = { closure: o.solvation, Na: 0, Cl: 0, detail: {} };
    if (o.solvation === 'born') {
      const f = (1 / o.epsP - 1 / EPS_T);
      out.Na = BORN0 / R_BORN.Na * f; out.Cl = BORN0 / R_BORN.Cl * f;
      out.detail = { aB_Na: R_BORN.Na, aB_Cl: R_BORN.Cl, epsP: o.epsP, epsB: EPS_T };
      return out;
    }
    let nNa, nCl;
    if (o.solvation === 'shell') {
      nNa = REF.nNa * shellFraction(R_SHELL.Na, g.Rw); nCl = REF.nCl * shellFraction(R_SHELL.Cl, g.Rw);
    } else {
      nNa = o.nNa != null ? o.nNa : p.nNa; nCl = o.nCl != null ? o.nCl : p.nCl;
    }
    const kNa = o.kNa != null ? o.kNa : lin.kNa, kCl = o.kCl != null ? o.kCl : lin.kCl;
    const lostNa = Math.max(0, REF.nNa - nNa), lostCl = Math.max(0, REF.nCl - nCl);
    out.Na = (1 - kNa) * (lostNa / REF.nNa) * G1.Na;
    out.Cl = (1 - kCl) * (lostCl / REF.nCl) * G1.Cl;
    out.detail = { nNa, nCl, lostNa, lostCl, kNa, kCl, nRefNa: REF.nNa, nRefCl: REF.nCl, G1Na: G1.Na, G1Cl: G1.Cl };
    return out;
  }

  /* build the solver input for a set of options (missing options take DEFAULTS) */
  function build(opts) {
    const o = Object.assign({}, DEFAULTS, opts || {});
    const p = presetOf(o.preset), g = geometry(p), step = o.step;
    const cL = o.cL != null ? o.cL : o.c, cR = o.cR != null ? o.cR : o.c;
    const s = {
      T, epsR: EPS_T,
      species: [{ name: 'Na+', z: 1, D: DT.Na }, { name: 'Cl-', z: -1, D: DT.Cl }],
      geom: { a: g.a * 1e-9, L: o.L * 1e-9, access: true, rCarbon: g.Rc * 1e-9 },
      cL: [cL, cL], cR: [cR, cR], V: o.V, dp: o.dp || 0, grid: { level: o.level },
    };
    const sv = solvation(o);
    if (step >= 2 && o.rimN > 0) s.rim = { n: o.rimN, w: o.rimW * 1e-9 };
    if (step >= 3) s.steric = { on: true, size: o.ionSize * 1e-9 };
    if (step >= 4) s.solv = { mode: o.solvation, dG: [sv.Na * 1000, sv.Cl * 1000] };
    if (step >= 5) s.Dpore = { on: true, ratio: [o.Dratio, o.Dratio] };
    s.eof = { on: step >= 6, mu: ETA_T, b: o.slip * 1e-9 };
    return { s, o, preset: p, geometry: g, solvation: sv };
  }

