  /* reported selectivity: GHK inversion of the reversal potential under the 10:1 gradient, with reservoir activities
     when the finite-size term is on (γ = 1/(1 − ṽ Σc), the same for both ions). Ratios above 10⁴, or a reversal
     potential at or beyond the Nernst limit within the solver's tolerance, are reported as "> 10⁴". */
  /* GHK-equivalent Na⁺/Cl⁻ permeability ratio of a reversal potential computed under the selectivity gradient
     (feed c, permeate c/gradient), with a status that says how to read it:
       finite       10⁻⁴ ≤ ratio ≤ 10⁴, shown to three significant figures;
       above_limit / below_limit   a positive ratio beyond the display range (> 10⁴ / < 10⁻⁴);
       nernst_na / nernst_cl       V_rev within NERNST_BAND of the Na⁺ or Cl⁻ Nernst potential of the reservoir
                                   activities, where the ratio diverges or vanishes;
       invalid      V_rev beyond a Nernst potential: no positive GHK ratio reproduces it (the raw ratio is negative);
       not_found    no reversal potential.
     The ratio is an effective descriptor of the model (constant-field GHK), not a measured permeability. */
  const NERNST_BAND = 1e-9;                                                   // V
  const SEL_DISPLAY_MAX = 1e4;
  const SEL_TEXT = { nernst_na: '> 10⁴', above_limit: '> 10⁴', nernst_cl: '< 10⁻⁴', below_limit: '< 10⁻⁴', invalid: 'outside GHK range', not_found: '–' };
  function selectivity(opts, Vrev) {
    const o = Object.assign({}, DEFAULTS, opts || {});
    const cL = o.c / 1000, cR = o.c / o.gradient / 1000;                      // mol L⁻¹
    let gL = 1, gR = 1;
    if (o.step >= 3) { const v = K.NA * Math.pow(o.ionSize * 1e-9, 3) * 1000; gL = 1 / (1 - v * 2 * cL); gR = 1 / (1 - v * 2 * cR); }
    const nernstNa = (RT / K.F) * Math.log((cR * gR) / (cL * gL));          // perfect cation selectivity
    const nernstCl = -nernstNa;                                               // perfect anion selectivity
    const lo = Math.min(nernstNa, nernstCl), hi = Math.max(nernstNa, nernstCl);
    const out = { Vrev, gL, gR, nernst: nernstNa, nernstNa, nernstCl, band: NERNST_BAND, ratio: NaN, beyond: 0 };
    let status;
    if (!isFinite(Vrev)) status = 'not_found';
    else {
      out.ratio = Core.ghkRatio(Vrev, cL, cR, T, gL, gR);
      if (Math.abs(Vrev - nernstNa) <= NERNST_BAND) status = 'nernst_na';
      else if (Math.abs(Vrev - nernstCl) <= NERNST_BAND) status = 'nernst_cl';
      else if (Vrev < lo || Vrev > hi || !(out.ratio > 0) || !isFinite(out.ratio)) { status = 'invalid'; out.beyond = Vrev < lo ? lo - Vrev : Math.max(0, Vrev - hi); }
      else if (out.ratio > SEL_DISPLAY_MAX) status = 'above_limit';
      else if (out.ratio < 1 / SEL_DISPLAY_MAX) status = 'below_limit';
      else status = 'finite';
    }
    out.status = status;
    out.capped = status !== 'finite';
    out.text = status === 'finite' ? Number(out.ratio).toPrecision(3) : SEL_TEXT[status];
    return out;
  }

