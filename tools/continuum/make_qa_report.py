#!/usr/bin/env python3
"""Write tools/continuum/QA_REPORT.md from the machine-readable results (no number is typed by hand); with --readme also
rewrite the results block of CONTINUUM_LAB_README.md (between its BEGIN:results and END:results markers).
Usage: python3 make_qa_report.py [--out QA_REPORT.md] [--readme]"""
import argparse, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
R = lambda f: (json.load(open(os.path.join(HERE, 'results', f))) if os.path.exists(os.path.join(HERE, 'results', f)) else None)


def crit():
    out = {}
    for line in open(os.path.join(HERE, 'TOLERANCES.md')):
        m = re.match(r'^\|\s*([A-Z]\d+)\s*\|\s*([^|]+?)\s*\|\s*(.+?)\s*\|\s*$', line)
        if m: out[m.group(1)] = (m.group(2), m.group(3).replace('**', ''))
    return out


def convergence_verdict(an):
    """The statement written by compare_openfoam.py (single source)."""
    return 'Grid convergence index: Roache, three grids, safety factor 1.25. Conclusion: %s.' % an.get('statement', 'not available')


def table(res, ids, cr):
    rows = ['| # | Check | Criterion | Measured | Result |', '|---|---|---|---|---|']
    n = {'PASS': 0, 'FAIL': 0, 'NOT_RUN': 0}
    for i in ids:
        it = next((x for x in (res or {}).get('items', []) if x['id'] == i), None)
        v = it['verdict'] if it else 'NOT_RUN'
        n[v] = n.get(v, 0) + 1
        rows.append('| %s | %s | %s | %s | **%s** |' % (i, cr.get(i, ('', ''))[0], cr.get(i, ('', ''))[1].replace('|', '∣'), (it['detail'] if it else 'not run').replace('|', '∣'), v))
    return '\n'.join(rows), n


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', default=os.path.join(HERE, 'QA_REPORT.md'))
    ap.add_argument('--readme', action='store_true', help='also rewrite the results block of CONTINUUM_LAB_README.md')
    a = ap.parse_args()
    cr = crit()
    groups = [('Network and core modules (Node) — `node tools/continuum/tests/t_core.js`', 't_core.json', ['N%d' % i for i in range(1, 10)]),
              ('Continuum solver (Node) — `node tools/continuum/tests/t_solver.js`', 't_solver.json', ['S%d' % i for i in range(1, 16)]),
              ('Decision rules of the resolution check (Node) — `node tools/continuum/tests/t_decision.js`', 't_decision.json', ['D1', 'D2', 'D3']),
              ('Native comparison (OpenFOAM v1912) — `sh tools/continuum/openfoam/run_all.sh`', 'openfoam.json', ['F1', 'F2', 'F3', 'F4']),
              ('Browser and regression (Chromium) — `node tools/continuum/tests/browser_continuum.js`', 'browser.json', ['B%d' % i for i in range(1, 14)] + ['R1']),
              ('Calibration and analysis tools — `sh tools/continuum/tests/t_tools.sh`', 't_tools.json', ['A1', 'A2', 'A3'])]
    out = ['# Continuum Lab — QA report (release 2026.6)', '',
           'Generated by `tools/continuum/make_qa_report.py` from `tools/continuum/results/*.json`. Criteria were frozen in',
           '`TOLERANCES.md` before evaluation; amendments are listed there with their reasons, and original failing results are kept',
           '(`results/t_solver.run1-frozen.json`, `results/browser.run1.json`).', '']
    tot = {'PASS': 0, 'FAIL': 0, 'NOT_RUN': 0}
    body = []
    for title, f, ids in groups:
        res = R(f)
        t, n = table(res, ids, cr)
        for k in tot: tot[k] += n.get(k, 0)
        body += ['## ' + title, '', t, '']
        if res and res.get('environment'): body += ['Environment: ' + res['environment'], '']
        if res and res.get('convergence') and res['convergence'].get('analysis', {}).get('browser'):
            cv = res['convergence']; an = cv['analysis']
            body += ['Reported mesh-convergence study (not a gate), closed-strip case:', '', '| Cells across W | Q browser (m³/s) | Q OpenFOAM (m³/s) | Q difference | Velocity L2 |', '|---|---|---|---|---|']
            body += ['| %d | %.6e | %.6e | %.3f %% | %.2f %% |' % (c['N'], c['Q_browser'], c['Q_openfoam'], 100 * c['Q_rel_diff'], 100 * c['velocity_L2']) for c in cv['levels']]
            body += ['', 'Observed order: browser %.2f, OpenFOAM %.2f. Richardson-extrapolated Q: browser %.6e, OpenFOAM %.6e m³/s (difference %.2f %%). %s'
                     % (an['browser']['observed_order'], an['openfoam']['observed_order'], an['browser']['Q_extrapolated_m3_s'], an['openfoam']['Q_extrapolated_m3_s'], 100 * an.get('extrapolated_rel_diff', float('nan')), convergence_verdict(an)), '']
    out += ['**Summary: %d PASS, %d FAIL, %d NOT_RUN** of %d acceptance checks.' % (tot['PASS'], tot['FAIL'], tot['NOT_RUN'], sum(tot.values())), ''] + body
    run1 = R('t_solver.run1-frozen.json')
    if run1:
        s14 = next(x for x in run1['items'] if x['id'] == 'S14')
        out += ['## Original results kept', '', '- First official solver run with the frozen S14 criterion: **%s** — %s' % (s14['verdict'], s14['detail'])]
        b1 = R('browser.run1.json')
        if b1:
            for it in b1['items']:
                if it['verdict'] != 'PASS': out.append('- First browser run, %s: **%s** — %s (fixed: grid items of the results column could not shrink below their table width; the tables now scroll inside their panels).' % (it['id'], it['verdict'], it['detail']))
        out.append('')
    mc = json.load(open(os.path.join(HERE, '..', '..', 'lab', 'continuum', 'data', 'mesh-check.json'))) if os.path.exists(os.path.join(HERE, '..', '..', 'lab', 'continuum', 'data', 'mesh-check.json')) else None
    if mc:
        e = mc['entries'].values()
        out += ['## Mesh check for every allowed size (`node tools/continuum/mesh_check.js`)', '',
                '%d sizes (W, B in {1, 2, 5, …, 1000} µm, aspect 1, 2 or 4), intact membrane: largest |Q_fine − Q_20| / Q_fine = %.2e (gate 0.02); largest port Reynolds number at 1 MPa %.3f; smallest membrane share of the resistance %.6f.'
                % (len(mc['entries']), max(x['rel'] for x in e), max(x['Re20'] for x in e), min(x['membraneShare20'] for x in e)), '']
    b = R('benchmark.json')
    if b:
        out += ['## Solve times (`node tools/continuum/tests/bench_browser.js`)', '', '| Case | Cells per chamber | Unknowns | Iterations | Worker (s) | Round trip (s) |', '|---|---|---|---|---|---|']
        out += ['| %s | %s | %d | %d | %.2f | %.2f |' % (r['case'], r['cells'], r['unknowns'], r['iterations'], r['worker_s'], r['roundTrip_s']) for r in b['rows']]
        out += ['', 'Chromium %s, %s (%d cores). %s' % (b['chromium'], b['cpu'], b['cores'], b['note']), '']
    pilot = os.path.join(HERE, 'md-calibration', 'pilot_summary.json')
    if os.path.exists(pilot):
        p = json.load(open(pilot))
        out += ['## Molecular calibration pilot (functionality only, not a measurement)', '', p.get('summary', ''), '']
    out += ['## Not run', '', '- Safari, Firefox, real phones and tablets, screen readers.', '- The molecular calibration campaign itself (480 ns of production; see `md-calibration/README.md`): the pore law stays illustrative.',
            '- Live confined MD in the browser (not implemented in this release; see the handoff).', '']
    open(a.out, 'w').write('\n'.join(out) + '\n')
    print('wrote', a.out, tot)
    if a.readme:
        readme_block(tot)


SUP = str.maketrans('-0123456789', '⁻⁰¹²³⁴⁵⁶⁷⁸⁹')


def sci(x):
    """3 significant figures; powers of ten written out outside 10^-3 .. 10^3."""
    if x == 0 or 1e-3 <= abs(x) < 1e3:
        return '%.3g' % x
    m, e = ('%.2e' % x).split('e')
    return '%s × 10%s' % (m, str(int(e)).translate(SUP))


def readme_block(tot):
    """Short results section for CONTINUUM_LAB_README.md, from the same result files."""
    path = os.path.join(HERE, '..', '..', 'CONTINUUM_LAB_README.md')
    txt = open(path).read()
    b0, b1 = '<!-- BEGIN:results', '<!-- END:results -->'
    i, j = txt.index(b0), txt.index(b1)
    head = txt[i:txt.index('-->', i) + 3]
    get = lambda f, k: next((x for x in (R(f) or {}).get('items', []) if x['id'] == k), None)
    lines = ['## Results of this release (generated)', '',
             '%d PASS, %d FAIL, %d NOT_RUN of %d acceptance checks; every number and verdict is in `tools/continuum/QA_REPORT.md` and `tools/continuum/results/`.' % (tot['PASS'], tot['FAIL'], tot['NOT_RUN'], sum(tot.values())), '']
    of = R('openfoam.json') or {}
    for k in ('F1', 'F2', 'F3', 'F4'):
        it = get('openfoam.json', k)
        if it:
            d = it.get('data', {})
            lines.append('- %s %s: **%s** — relative Q difference %s, velocity normalised L2 %s.' % (k, it['name'], it['verdict'], sci(d.get('Q_rel_diff', float('nan'))), sci(d.get('velocity_L2', float('nan')))))
    cv = of.get('convergence', {})
    an = cv.get('analysis', {})
    if an.get('browser'):
        lines.append('- Reported convergence study (closed strip, 20/40/80 cells; not a gate): Q difference %s; observed order %.2f (browser) and %.2f (OpenFOAM); %s.'
                     % (', '.join('%.2f %%' % (100 * c['Q_rel_diff']) for c in cv['levels']), an['browser']['observed_order'], an['openfoam']['observed_order'], an.get('statement', '')))
    mc_path = os.path.join(HERE, '..', '..', 'lab', 'continuum', 'data', 'mesh-check.json')
    if os.path.exists(mc_path):
        e = list(json.load(open(mc_path))['entries'].values())
        lines.append('- Mesh check, all %d allowed sizes (pore-limited devices): refining the mesh changes Q by at most %s (relative); the chambers carry at most %s of the resistance.'
                     % (len(e), sci(max(x['rel'] for x in e)), sci(max(1 - x['membraneShare20'] for x in e))))
    b = R('benchmark.json')
    if b:
        lines.append('- Solve times in the page worker (headless Chromium, build machine): ' + '; '.join('%s %.2f s' % (r['case'], r['worker_s']) for r in b['rows']) + '.')
    pilot = os.path.join(HERE, 'md-calibration', 'pilot_summary.json')
    if os.path.exists(pilot):
        p = json.load(open(pilot)); pl = p['pilot_from_empty_tube']
        lines.append('- Molecular pilot (functionality only): %.2f–%.2f ns/day on one core; tube occupancy %.2f molecules averaged over 10–%.0f ps from an empty start (not filled; see `md-calibration/README.md`).'
                     % (p['speed_ns_per_day']['min'], p['speed_ns_per_day']['max'], pl['mean_occupancy'], pl['length_ps']))
    new = head + '\n' + '\n'.join(lines) + '\n' + b1
    open(path, 'w').write(txt[:i] + new + txt[j + len(b1):])
    print('updated', os.path.relpath(path))


if __name__ == '__main__':
    main()
