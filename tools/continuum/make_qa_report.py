#!/usr/bin/env python3
"""Write tools/continuum/QA_REPORT.md from the machine-readable results (no number is typed by hand); with --readme also
rewrite the results block of CONTINUUM_LAB_README.md (between its BEGIN:results and END:results markers).
Since release 2026.12.2 the public Continuum Lab is the flow comparison only; the ion-transport and membrane experiments,
with their criteria, tests and records, are in the development archive (outside the deployment) and in the repository
history. Their last results are quoted from the archived QA report, not counted here.
Usage: python3 make_qa_report.py [--out QA_REPORT.md] [--readme]"""
import argparse, glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
R = lambda f: (json.load(open(os.path.join(HERE, 'results', f))) if os.path.exists(os.path.join(HERE, 'results', f)) else None)
RELEASE = '2026.12.2'
ARCHIVE = '`continuum-development-archive-2026.12.1.zip` (kept outside the deployment) and the repository history up to commit eb698af'
RETIRED = [  # quoted from the archived QA report of release 2026.12.1 (111 PASS, 3 FAIL, 0 NOT_RUN of 114 for all three experiments)
    ('Ion transport through one nanotube pore (`lab/continuum/`)', 'I1–I19, IB1–IB13', '32 of 32 PASS'),
    ('Water flow through a nanotube membrane (`lab/continuum/water.html`)', 'N1–N9, S1–S15, D1–D3, F1–F4, B1–B16, R1, A1–A5', '50 of 53 PASS; **F2, F3 and F4 FAIL** (comparisons with OpenFOAM), kept as failures')]


def crit():
    out = {}
    for line in open(os.path.join(HERE, 'flow', 'TOLERANCES.md')):
        m = re.match(r'^\|\s*([A-Z]{1,2}\d+)\s*\|\s*([^|]+?)\s*\|\s*(.+?)\s*\|\s*$', line)
        if m: out[m.group(1)] = (m.group(2), m.group(3).replace('**', ''))
    return out


def table(res, ids, cr):
    rows = ['| # | Check | Criterion | Measured | Result |', '|---|---|---|---|---|']
    n = {'PASS': 0, 'FAIL': 0, 'NOT_RUN': 0}
    for i in ids:
        it = next((x for x in (res or {}).get('items', []) if x['id'] == i), None)
        v = it['verdict'] if it else 'NOT_RUN'
        n[v] = n.get(v, 0) + 1
        rows.append('| %s | %s | %s | %s | **%s** |' % (i, cr.get(i, ('', ''))[0], cr.get(i, ('', ''))[1].replace('|', '∣'), (it['detail'] if it else 'not run').replace('|', '∣'), v))
    return '\n'.join(rows), n


def pb_ids(cr):
    return sorted((k for k in cr if re.match(r'^PB\d+$', k)), key=lambda k: int(k[2:]))


def kept_records():
    names = sorted(os.path.basename(p) for p in glob.glob(os.path.join(HERE, 'results', '*')))
    return [n for n in names if re.match(r'^(t_flow|browser_flow|flow_python)\.\d', n)]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', default=os.path.join(HERE, 'QA_REPORT.md'))
    ap.add_argument('--readme', action='store_true', help='also rewrite the results block of CONTINUUM_LAB_README.md')
    a = ap.parse_args()
    cr = crit()
    pb = pb_ids(cr)
    groups = [('Numerical verification (Node) — `node tools/continuum/flow/t_flow.js`', 't_flow.json', ['P%d' % i for i in range(1, 12)]),
              ('Source-curve reproduction (Node) — `node tools/continuum/flow/t_flow.js`', 't_flow.json', ['PR%d' % i for i in range(1, 7)]),
              ('This page in a browser (Chromium) — `node tools/continuum/flow/browser_flow.js`', 'browser_flow.json', pb)]
    kept = kept_records()
    out = ['# Continuum Lab — QA report (release %s)' % RELEASE, '',
           'Generated by `tools/continuum/make_qa_report.py` from `tools/continuum/results/*.json`. The public Continuum Lab is one',
           'published nanotube flow case (`lab/continuum/flow.html`; criteria in `flow/TOLERANCES.md`, written before the runs they',
           'govern; failing and superseded runs are kept). Superseded records of this experiment: ' + ', '.join('`results/%s`' % k for k in kept) + '.', '',
           'Ion transport and membrane flow were retired from the public site in release %s. Their criteria, tests and complete' % RELEASE,
           'records, including the three failing comparisons with OpenFOAM, are kept in ' + ARCHIVE + '.',
           'They are reported by experiment below and are not counted in this summary.', '']
    tot = {'PASS': 0, 'FAIL': 0, 'NOT_RUN': 0}
    body = []
    for title, f, ids in groups:
        res = R(f)
        t, n = table(res, ids, cr)
        for k in tot: tot[k] += n.get(k, 0)
        body += ['## ' + title, '', t, '']
        if res and res.get('environment'): body += ['Environment: ' + res['environment'], '']
        if f == 't_flow.json' and ids[0] == 'PR1' and res and res.get('reported'):
            body += flow_reported(res['reported'])
    out += ['**Summary (public Continuum Lab): %d PASS, %d FAIL, %d NOT_RUN** of %d acceptance checks.' % (tot['PASS'], tot['FAIL'], tot['NOT_RUN'], sum(tot.values())), '',
            '**Not established:** independent physical validation. It needs boundary inputs obtained independently of the driven run and an accuracy requirement written down for a stated use before the comparison.', ''] + body
    out += ['## Retired experiments (development archive; not part of this deployment)', '',
            '| Experiment | Checks | Last result (release 2026.12.1) |', '|---|---|---|']
    out += ['| %s | %s | %s |' % r for r in RETIRED]
    out += ['', 'These results are quoted from the archived QA report (`site-2026.12.1/tools/continuum/QA_REPORT.md` in the archive: 111 PASS, 3 FAIL, 0 NOT_RUN of 114 for the three experiments together). The F2–F4 failures stay failures.', '']
    out += ['## Not run', '', '- Safari, Firefox, real phones and tablets, screen readers.', '- Independent physical validation (see above).', '']
    open(a.out, 'w').write('\n'.join(out) + '\n')
    print('wrote', a.out, tot)
    if a.readme:
        readme_block(tot)


def dec(x, n):
    """n significant figures in plain decimal notation."""
    import math
    return '0' if x == 0 else '%.*f' % (max(0, n - 1 - int(math.floor(math.log10(abs(x))))), x)


def flow_reported(rp):
    """Agreement with molecular dynamics: numbers without a pass or fail, not counted in the summary."""
    fr, er = rp['flow_rate'], rp['entrance_resistance_c3']
    out = ['### Agreement with molecular dynamics (no pass or fail: no accuracy requirement exists)', '',
           'Default combination: %s. Flow rate: model %.4f ± %.5f pL/s, molecular dynamics %.4f ± %.4f pL/s, difference %+.1f ± %.1f %%.'
           % (rp['default_combination'], fr['model_pL_s'], fr['u_model_pL_s'], fr['md_pL_s'], fr['u_md_pL_s'], 100 * fr['rel'], 100 * fr['u_rel']),
           'Profile: root-mean-square difference %.1f %%, largest %+.1f %% (%d points). The ± values are extraction uncertainties from reading the published figures.'
           % (100 * rp['profile_rms_rel'], 100 * rp['profile_worst_rel'], sum(1 for q in rp['profile'] if q['rel'] is not None)),
           'Entrance-resistance sensitivity (c = 3, an assumed coefficient): %.1f %% of the flow remains (%.4f pL/s, %+.1f %% from molecular dynamics); equivalent slip length %.2f nm.'
           % (100 * er['interior_fraction'], er['Q_pL_s'], 100 * er['Q_rel_to_md'], er['equivalent_slip_length_nm']), '',
           '| Model | Boundary convention | Viscosity | Flow rate (pL/s) | Difference from MD | Profile, rms | Profile, largest |', '|---|---|---|---|---|---|---|']
    for c in rp['by_combination']:
        out.append('| %s | %s | %s | %s ± %s | %+.1f ± %.1f %% | %.1f %% | %+.1f %% |' % (c['family'].replace('_', ' '), 'D′ (first density peak)' if c['boundary'] == 'Dp' else 'D (carbon centres)', {'green_kubo': 'Green–Kubo'}.get(c['viscosity'], c['viscosity']),
                   dec(c['Q_pL_s'], 3), dec(c['u_Q_pL_s'], 2), 100 * c['Q_rel'], 100 * c['u_Q_rel'], 100 * c['profile_rms_rel'], 100 * c['profile_worst_rel']))
    out += ['', 'No accuracy requirement for a stated use has been defined, and the case is a published-case reconstruction (the slip velocity was measured in the same driven run as the reference), so these numbers carry no PASS or FAIL.', '']
    return out


def readme_block(tot):
    """Short results section for CONTINUUM_LAB_README.md, from the same result files."""
    path = os.path.join(HERE, '..', '..', 'CONTINUUM_LAB_README.md')
    txt = open(path).read()
    b0, b1 = '<!-- BEGIN:results', '<!-- END:results -->'
    i, j = txt.index(b0), txt.index(b1)
    head = txt[i:txt.index('-->', i) + 3]
    lines = ['## Results of this release (generated)', '',
             '%d PASS, %d FAIL, %d NOT_RUN of %d acceptance checks for the public Continuum Lab; every number and verdict is in `tools/continuum/QA_REPORT.md` and `tools/continuum/results/`.' % (tot['PASS'], tot['FAIL'], tot['NOT_RUN'], sum(tot.values())), '']
    tf, bf = R('t_flow.json'), R('browser_flow.json')
    if tf:
        ok = lambda items, pre: (sum(1 for x in items if x['id'].startswith(pre) and x['id'][len(pre):].isdigit() and x['verdict'] == 'PASS'), sum(1 for x in items if x['id'].startswith(pre) and x['id'][len(pre):].isdigit()))
        fr = tf['reported']['flow_rate']
        nb = ok(bf['items'], 'PB') if bf else None
        lines.append('- Numerical verification P1–P11 %d of %d PASS, source-curve reproduction PR1–PR6 %d of %d PASS, browser %s. Reported without a pass or fail: flow rate of the default combination %+.1f ± %.1f %% from the published molecular dynamics (extraction uncertainty), profile rms %.1f %%. Independent physical validation: not established.'
                     % (ok(tf['items'], 'P') + ok(tf['items'], 'PR') + (('PB1–PB%d %d of %d PASS' % (nb[1], nb[0], nb[1])) if nb else 'not run', 100 * fr['rel'], 100 * fr['u_rel'], 100 * tf['reported']['profile_rms_rel'])))
    for name, checks, result in RETIRED:
        lines.append('- Retired, in the development archive: %s, %s: %s.' % (name, checks, result))
    new = head + '\n' + '\n'.join(lines) + '\n' + b1
    open(path, 'w').write(txt[:i] + new + txt[j + len(b1):])
    print('updated', os.path.relpath(path))


if __name__ == '__main__':
    main()
