#!/usr/bin/env python3
"""Write the native OpenFOAM v1912 (OpenCFD) reference cases for the Continuum Lab (TOLERANCES.md F1-F4).

  F1_duct          developed square duct, 24 x 24 x 12 cells, pressure inlet/outlet, no-slip walls (browser test S1)
  F2_uniform       two-chamber device, 2 um x 2 um, 20 x 20 x 10 cells per chamber, quarter ports, uniform
                   porousBafflePressure membrane with Rs chosen so that chambers and membrane share the resistance
  F3_strip         F2 with a closed strip (columns 8-11 of 20: wall baffles) and porous baffles elsewhere
  F4_strip_fine    F3 on the refined mesh (40 x 40 x 20 cells per chamber)
  F5_strip_80      F3 on 80 x 80 x 40 cells per chamber, reported convergence study only (not a gate); looser inner-solver
                   settings (GAMG relTol 0.01, residualControl p 1e-10) and a write every 250 iterations to follow Q

Same physical case as the browser solver: water at 300 K (rho 996.557 kg/m3, mu 853.742e-6 Pa s), outlet-referenced
pressure (p = 0 at the outlet, p = dP at the inlet; OpenFOAM uses kinematic pressure p/rho), no-slip walls,
pressure ports with zero tangential velocity on inflow (pressureInletOutletVelocity). The porous baffle is a cyclic
pair, so the tangential velocity is continuous across the membrane; the browser comparison uses the matching
closure 'continuous-tangential'. porousBafflePressure (I = 0): kinematic jump = D nu L |U_n|, i.e. dp = D mu L J, so
D = Rs / (mu L) with L = 1 m here.

Membrane resistance of the comparison: Rs = 2.5e4 Pa s/m (the chambers then carry most of the resistance and the
flux is strongly non-uniform). In v1912 the porous-baffle jump is evaluated explicitly from the previous flux, with no
relaxation option; SIMPLE stalled for Rs = 1.0e5 and 2.5e5 on the 20-cell mesh (about 12 and 29 times mu/dz) and for
the first choice 6.7e5, while 2.5e4 converged in about 250 under-relaxed iterations. The browser solver treats the
interface implicitly and handles any Rs (test S3). Usage: python3 make_cases.py [--out DIR]
"""
import argparse, json, os

RHO, MU = 996.557, 853.742e-6
NU = MU / RHO
HDR = """/*--------------------------------*- C++ -*----------------------------------*\\
  OpenFOAM v1912 (OpenCFD) - Continuum Lab reference case, generated by make_cases.py
\\*---------------------------------------------------------------------------*/
FoamFile {{ version 2.0; format ascii; class {cls}; object {obj}; }}
"""

CASES = {
    'F1_duct': dict(kind='duct', W=1e-6, N=24, nzc=12, dP=1000.0),
    'F2_uniform': dict(kind='device', W=2e-6, B=2e-6, N=20, dP=1.0, Rs=2.5e4, closedCols=None),
    'F3_strip': dict(kind='device', W=2e-6, B=2e-6, N=20, dP=1.0, Rs=2.5e4, closedCols=(8, 12)),
    'F4_strip_fine': dict(kind='device', W=2e-6, B=2e-6, N=40, dP=1.0, Rs=2.5e4, closedCols=(16, 24)),
    # additional, reported only (not a gate): the strip case on a finer mesh, for the convergence study
    'F5_strip_80': dict(kind='device', W=2e-6, B=2e-6, N=80, dP=1.0, Rs=2.5e4, closedCols=(32, 48), pResidual=1e-10, pTol=1e-13, pRelTol=0.01, pMaxIter=100, writeInterval=250),
}


def w(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)


def common(case, endTime, writeInterval, relaxed=False, pResidual=1e-13, pTol=1e-14, pRelTol=0.001, pMaxIter=200):
    w(f'{case}/constant/transportProperties', HDR.format(cls='dictionary', obj='transportProperties') + f'transportModel Newtonian;\nnu {NU:.10e};\n')
    w(f'{case}/constant/turbulenceProperties', HDR.format(cls='dictionary', obj='turbulenceProperties') + 'simulationType laminar;\n')
    w(f'{case}/system/controlDict', HDR.format(cls='dictionary', obj='controlDict') + f"""application simpleFoam;
startFrom startTime; startTime 0; stopAt endTime; endTime {endTime}; deltaT 1;
writeControl timeStep; writeInterval {writeInterval}; purgeWrite {1 if writeInterval >= endTime else 2}; writeFormat ascii; writePrecision 14;
writeCompression off; timeFormat general; timePrecision 8; runTimeModifiable false;
""")
    w(f'{case}/system/fvSchemes', HDR.format(cls='dictionary', obj='fvSchemes') + """ddtSchemes { default steadyState; }
gradSchemes { default Gauss linear; }
divSchemes { default none; div(phi,U) bounded Gauss linear; div((nuEff*dev2(T(grad(U))))) Gauss linear; }
laplacianSchemes { default Gauss linear corrected; }
interpolationSchemes { default linear; }
snGradSchemes { default corrected; }
""")
    w(f'{case}/system/fvSolution', HDR.format(cls='dictionary', obj='fvSolution') + """solvers
{
    p { solver GAMG; smoother GaussSeidel; tolerance %(pTol)g; relTol %(pRelTol)g; maxIter %(pMaxIter)d; }
    U { solver PBiCGStab; preconditioner DILU; tolerance 1e-16; relTol 0.001; maxIter 200; }
}
SIMPLE { nNonOrthogonalCorrectors 0; consistent %(cons)s; residualControl { p %(pres)g; } }
relaxationFactors { %(relax)s }
""" % dict(pTol=pTol, pRelTol=pRelTol, pMaxIter=pMaxIter, pres=pResidual, cons='no' if relaxed else 'yes', relax='equations { U 0.7; } fields { p 0.3; }' if relaxed else 'equations { U 0.9; ".*" 0.9; } fields { p 1; }'))


def duct(case, c):
    W, N, nzc = c['W'], c['N'], c['nzc']
    L = W * nzc / N
    w(f'{case}/system/blockMeshDict', HDR.format(cls='dictionary', obj='blockMeshDict') + f"""convertToMeters 1;
vertices ( (0 0 0) ({W} 0 0) ({W} {W} 0) (0 {W} 0) (0 0 {L}) ({W} 0 {L}) ({W} {W} {L}) (0 {W} {L}) );
blocks ( hex (0 1 2 3 4 5 6 7) ({N} {N} {nzc}) simpleGrading (1 1 1) );
boundary
(
    inlet {{ type patch; faces ((4 5 6 7)); }}
    outlet {{ type patch; faces ((0 3 2 1)); }}
    walls {{ type wall; faces ((0 1 5 4) (1 2 6 5) (2 3 7 6) (3 0 4 7)); }}
);
""")
    pin = c['dP'] / RHO
    w(f'{case}/0/p', HDR.format(cls='volScalarField', obj='p') + f"""dimensions [0 2 -2 0 0 0 0];
internalField uniform 0;
boundaryField
{{
    inlet {{ type fixedValue; value uniform {pin:.12e}; }}
    outlet {{ type fixedValue; value uniform 0; }}
    walls {{ type zeroGradient; }}
}}
""")
    w(f'{case}/0/U', HDR.format(cls='volVectorField', obj='U') + """dimensions [0 1 -1 0 0 0 0];
internalField uniform (0 0 0);
boundaryField
{
    inlet { type pressureInletOutletVelocity; value uniform (0 0 0); }
    outlet { type pressureInletOutletVelocity; value uniform (0 0 0); }
    walls { type noSlip; }
}
""")
    common(case, 4000, 4000)
    w(f'{case}/Allrun', '#!/bin/sh\nset -e\ncd "$(dirname "$0")"\nblockMesh > log.blockMesh 2>&1\nsimpleFoam > log.simpleFoam 2>&1\n')


def device(case, c):
    W, B, N = c['W'], c['B'], c['N']
    Lmin = min(W, B); nx, ny = round(N * W / Lmin), round(N * B / Lmin); H = 0.5 * Lmin; nz = round(N * H / Lmin)
    dx, dy, dz = W / nx, B / ny, H / nz
    half = N // 10
    i0, i1, j0, j1 = nx // 2 - half, nx // 2 + half, ny // 2 - half, ny // 2 + half
    e = 0.25 * dz
    w(f'{case}/system/blockMeshDict', HDR.format(cls='dictionary', obj='blockMeshDict') + f"""convertToMeters 1;
vertices ( (0 0 {-H}) ({W} 0 {-H}) ({W} {B} {-H}) (0 {B} {-H}) (0 0 {H}) ({W} 0 {H}) ({W} {B} {H}) (0 {B} {H}) );
blocks ( hex (0 1 2 3 4 5 6 7) ({nx} {ny} {2 * nz}) simpleGrading (1 1 1) );
boundary
(
    walls {{ type wall; faces ((4 5 6 7) (0 3 2 1) (0 1 5 4) (1 2 6 5) (2 3 7 6) (3 0 4 7)); }}
);
""")
    w(f'{case}/system/topoSetDict', HDR.format(cls='dictionary', obj='topoSetDict') + f"""actions
(
    {{ name inletFaces; type faceSet; action new; source boxToFace; box ({i0 * dx} {j0 * dy} {H - e}) ({i1 * dx} {j1 * dy} {H + e}); }}
    {{ name outletFaces; type faceSet; action new; source boxToFace; box ({i0 * dx} {j0 * dy} {-H - e}) ({i1 * dx} {j1 * dy} {-H + e}); }}
);
""")
    w(f'{case}/system/createPatchDict', HDR.format(cls='dictionary', obj='createPatchDict') + """pointSync false;
patches
(
    { name inlet; patchInfo { type patch; } constructFrom set; set inletFaces; }
    { name outlet; patchInfo { type patch; } constructFrom set; set outletFaces; }
);
""")
    D = c['Rs'] / (MU * 1.0)
    # membrane regions: open plates (porous cyclic pairs) and the closed strip (wall pair)
    regions = []
    if c['closedCols']:
        a, b = c['closedCols']
        regions.append(('openA', 0, a * dx, 'porous'))
        regions.append(('closed', a * dx, b * dx, 'wall'))
        regions.append(('openB', b * dx, W, 'porous'))
    else:
        regions.append(('open', 0, W, 'porous'))
    baffles = []
    for name, xa, xb, kind in regions:
        plate = f'type searchableSurface; surface searchablePlate; origin ({xa} 0 0); span ({xb - xa} {B} 0);'
        if kind == 'wall':
            baffles.append(f"""    {name}
    {{
        {plate}
        patchPairs {{ type wall; patchFields {{ U {{ type noSlip; }} p {{ type zeroGradient; }} }} }}
    }}""")
        else:
            baffles.append(f"""    {name}
    {{
        {plate}
        patches
        {{
            master
            {{
                name {name}_master; type cyclic; neighbourPatch {name}_slave;
                patchFields
                {{
                    p {{ type porousBafflePressure; patchType cyclic; jump uniform 0; value uniform 0; D {D:.10e}; I 0; length 1; uniformJump false; }}
                    U {{ type cyclic; value uniform (0 0 0); }}
                }}
            }}
            slave
            {{
                name {name}_slave; type cyclic; neighbourPatch {name}_master;
                patchFields
                {{
                    p {{ type porousBafflePressure; patchType cyclic; value uniform 0; D {D:.10e}; I 0; length 1; uniformJump false; }}
                    U {{ type cyclic; value uniform (0 0 0); }}
                }}
            }}
        }}
    }}""")
    w(f'{case}/system/createBafflesDict', HDR.format(cls='dictionary', obj='createBafflesDict') + 'internalFacesOnly true;\nbaffles\n{\n' + '\n'.join(baffles) + '\n}\n')
    pin = c['dP'] / RHO
    w(f'{case}/0/p', HDR.format(cls='volScalarField', obj='p') + f"""dimensions [0 2 -2 0 0 0 0];
internalField uniform 0;
boundaryField
{{
    inlet {{ type fixedValue; value uniform {pin:.12e}; }}
    outlet {{ type fixedValue; value uniform 0; }}
    walls {{ type zeroGradient; }}
}}
""")
    w(f'{case}/0/U', HDR.format(cls='volVectorField', obj='U') + """dimensions [0 1 -1 0 0 0 0];
internalField uniform (0 0 0);
boundaryField
{
    inlet { type pressureInletOutletVelocity; value uniform (0 0 0); }
    outlet { type pressureInletOutletVelocity; value uniform (0 0 0); }
    walls { type noSlip; }
}
""")
    common(case, 3000 if c['N'] <= 20 else (8000 if c['N'] <= 40 else 20000), c.get('writeInterval', 20000), relaxed=True, pResidual=c.get('pResidual', 1e-13), pTol=c.get('pTol', 1e-14),
           pRelTol=c.get('pRelTol', 0.001), pMaxIter=c.get('pMaxIter', 200))
    w(f'{case}/Allrun', '#!/bin/sh\nset -e\ncd "$(dirname "$0")"\nblockMesh > log.blockMesh 2>&1\ntopoSet > log.topoSet 2>&1\ncreatePatch -overwrite > log.createPatch 2>&1\ncreateBaffles -overwrite > log.createBaffles 2>&1\nsimpleFoam > log.simpleFoam 2>&1\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cases'), help='output directory (default: ./cases)')
    a = ap.parse_args()
    for name, c in CASES.items():
        case = os.path.join(a.out, name)
        (duct if c['kind'] == 'duct' else device)(case, c)
        os.chmod(os.path.join(case, 'Allrun'), 0o755)
        w(os.path.join(case, 'case.json'), json.dumps(dict(c, name=name, rho=RHO, mu=MU, nu=NU, foamVersion='OpenFOAM v1912 (OpenCFD)', solver='simpleFoam (laminar, SIMPLEC)',
                                                     porousBaffle='porousBafflePressure, I = 0, length = 1 m, D = Rs/(mu L)' if c['kind'] == 'device' else None), indent=1))
        print('wrote', case)


if __name__ == '__main__':
    main()
